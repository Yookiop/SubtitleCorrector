/*
 * SubtitleCorrector - popup.
 * Toont de status van de actieve YouTube-tab en kan de correctie handmatig starten.
 */
'use strict';

const L = globalThis.SCLang;
const $ = (id) => document.getElementById(id);
let lastState = null;

function setText(id, text, cls) {
  const el = $(id);
  el.textContent = text;
  el.className = 'v' + (cls ? ' ' + cls : '');
}

function activeTab() {
  return new Promise((resolve) => {
    chrome.tabs.query({ active: true, currentWindow: true }, (tabs) => resolve(tabs && tabs[0] ? tabs[0] : null));
  });
}

function sendToTab(tabId, msg) {
  return new Promise((resolve) => {
    try {
      chrome.tabs.sendMessage(tabId, msg, (res) => {
        void chrome.runtime.lastError;
        resolve(res || null);
      });
    } catch (e) {
      resolve(null);
    }
  });
}

function sendBg(msg) {
  return new Promise((resolve) => {
    try {
      chrome.runtime.sendMessage(msg, (res) => {
        void chrome.runtime.lastError;
        resolve(res || null);
      });
    } catch (e) {
      resolve(null);
    }
  });
}

function labelTrack(cur, shown) {
  if (!cur) return 'uit';
  const kind = cur.isAutoGenerated ? 'auto' : 'handmatig';
  let s = L.shortLabel(cur.languageCode) + ' (' + kind + ')';
  if (cur.translated) s += ' -> vertaald naar ' + L.shortLabel(cur.translatedTo);
  // Een gekozen track is niet hetzelfde als een zichtbare ondertitel: YouTube
  // kan de track onthouden (menu aangevinkt) terwijl het CC-knopje uit staat.
  if (shown === false) s += ' - weergave uit';
  return s;
}

function labelAudio(probe) {
  if (!probe) return 'onbekend';
  const det = L.detectAudioLanguage(probe);
  const parts = [];
  if (det.lang) {
    const src = {
      'audio-track': 'audiotrack',
      'current-asr': 'ASR-track',
      'asr-track': 'ASR-track',
      'default-audio-language': 'video-metadata'
    }[det.source] || det.source;
    parts.push(L.shortLabel(det.lang) + ' (' + src + ')');
  } else {
    parts.push('onbekend');
  }
  if (probe.audioTrack && probe.audioTrack.isAutoDubbed) parts.push('dub');
  if (det.ambiguous) parts.push('tegenstrijdig');
  return parts.join(' ');
}

/** Regel "Dubbelcheck": wat heeft de audio-controle opgeleverd? */
function labelVerify(rec, enabled) {
  if (!enabled) return { text: 'uit', cls: 'muted' };
  if (!rec) return { text: 'nog niet gecheckt', cls: 'muted' };
  const found = L.shortLabel(rec.found || rec.lang);
  switch (rec.status) {
    case 'confirmed': return { text: found + ' bevestigd (audio)', cls: 'ok' };
    case 'corrected': return { text: 'gecorrigeerd naar ' + found, cls: 'warn' };
    case 'no-bridge': return { text: 'bridge niet klaar', cls: 'muted' };
    case 'skipped': return { text: 'overgeslagen (playlist)', cls: 'muted' };
    case 'inconclusive': return { text: 'onduidelijk (audio)', cls: 'warn' };
    default: return { text: 'nog niet gecheckt', cls: 'muted' };
  }
}

/** Regel "Eigen weergave": tekent Caption Boost, of staat YouTube's venster er? */
function labelBoost(diag) {
  if (!diag) return { text: 'onbekend', cls: 'muted' };
  const d = diag.drawing || {};
  if (!d.cboostOn) return { text: 'uit (optie Caption Boost)', cls: 'muted' };
  // Een page agent zonder recente frames (tabblad op de achtergrond, of de
  // extensie is herladen zonder de pagina te verversen) houdt rafActive op
  // true staan; de leeftijd van het laatste frame verraadt het.
  if (typeof d.frameAgeMs === 'number' && d.frameAgeMs > 10000) {
    return { text: 'stil (' + Math.round(d.frameAgeMs / 1000) + ' s geen frame)', cls: 'err' };
  }
  if (d.rafActive) return { text: 'eigen weergave actief', cls: 'ok' };
  const last = diag.boost && diag.boost.lastStop;
  const why = last && last.reason ? ' (' + last.reason + ')' : '';
  if (diag.trackCaptured) return { text: 'track klaar, wacht op tekenen', cls: 'warn' };
  return { text: "YouTube's venster" + why, cls: 'warn' };
}

/** Regel "Vertraging": hoeveel woorden staat de weergave achter op de klok? */
function labelLag(diag) {
  const lag = diag && diag.renderLag;
  if (!diag || !diag.drawing || !diag.drawing.rafActive || !lag) return { text: 'n.v.t.', cls: 'muted' };
  const pending = typeof lag.pending === 'number' ? lag.pending : 0;
  const text = pending <= 1 ? 'bij (0-1 woord)' : pending + ' woorden achter';
  return { text: text, cls: pending <= 1 ? 'ok' : (pending <= 4 ? 'warn' : 'err') };
}

/** Regel "Track opgevangen": is de timedtext-track van deze video binnen? */
function labelCaptured(diag) {
  if (!diag) return { text: 'onbekend', cls: 'muted' };
  if (diag.trackCaptured) return { text: 'ja', cls: 'ok' };
  const ignored = (diag.timedtext && diag.timedtext.ignored) || {};
  const why = Object.keys(ignored).filter((k) => ignored[k] > 0);
  if (!diag.timedtext || !diag.timedtext.requests) return { text: 'nog geen verzoek', cls: 'muted' };
  return { text: 'nee' + (why.length ? ' (' + why.join(', ') + ')' : ''), cls: 'warn' };
}

/** Regel "Prestatie": haperingen van de pagina — en of die van ons komen. */
function labelJank(diag) {
  const j = diag && diag.jank;
  if (!j) return { text: 'onbekend', cls: 'muted' };
  if (!j.longFrames) return { text: 'geen haperingen', cls: 'ok' };
  const worst = (j.worst && j.worst.ms) || 0;
  const own = Math.round(j.mineMs || 0);
  const text = j.longFrames + (j.longFrames === 1 ? ' lange frame' : ' lange frames') +
    ', ergste ' + worst + ' ms' + (own ? ' (eigen code ' + own + ' ms)' : '');
  return { text: text, cls: worst >= 500 ? 'err' : 'warn' };
}

async function render() {
  const tab = await activeTab();
  const settings = await new Promise((r) => chrome.storage.sync.get({ enabled: true, hotkey: ']', hotkeyEnabled: false, preferAutoGenerated: true, forceSubtitlesOn: true, audioFallback: true, captionWordByWord: true, doubleCheckLanguage: true }, r));

  const hotkeyOff = settings.hotkeyEnabled === false || !settings.hotkey;
  $('hotkey').textContent = hotkeyOff ? 'uit' : settings.hotkey;
  $('hotkeyNote').textContent = hotkeyOff
    ? ' - hotkey staat uit in de instellingen'
    : ' = ondertitels aan/uit (nog een keer = weer aan)';
  $('wordByWord').checked = !!settings.captionWordByWord;
  setText('enabled', settings.enabled ? 'aan' : 'uit', settings.enabled ? 'ok' : 'err');

  const health = await sendBg({ type: 'bridgeHealth' });
  if (health && health.capture === false) {
    setText('bridge', 'niet ondersteund (Firefox)', 'muted');
    setText('model', 'audio-analyse kan alleen in Chrome/Brave', 'muted');
  } else if (!health || !health.ok) {
    setText('bridge', 'offline', 'err');
    setText('model', health && health.url ? health.url : '-', 'muted');
  } else if (!health.ready) {
    setText('bridge', 'online (model laden...)', 'warn');
    setText('model', (health.backend || '?') + ' / ' + (health.model || '?'), 'muted');
  } else {
    setText('bridge', 'online', 'ok');
    setText('model', (health.backend || '?') + ' / ' + (health.model || '?'), 'muted');
  }

  if (!tab || !/^https:\/\/(www|m)\.youtube\.com\//.test(tab.url || '')) {
    setText('video', 'geen YouTube-tab');
    setText('audio', '-');
    setText('caption', '-');
    setText('action', '-');
    setText('check', '-');
    setText('boost', '-');
    setText('lag', '-');
    setText('track', '-');
    setText('jank', '-');
    $('apply').disabled = true;
    return;
  }

  const st = await sendToTab(tab.id, { type: 'popupState' });
  if (!st || !st.probe) {
    setText('video', 'extensie nog niet actief - ververs de pagina');
    setText('audio', '-');
    setText('caption', '-');
    setText('action', '-');
    setText('check', '-');
    setText('boost', '-');
    setText('lag', '-');
    setText('track', '-');
    setText('jank', '-');
    $('apply').disabled = true;
    return;
  }

  const probe = st.probe;
  lastState = st;
  $('apply').disabled = false;
  setText('video', probe.title ? (probe.title.length > 46 ? probe.title.slice(0, 46) + '...' : probe.title) : (probe.videoId || '-'));
  setText('audio', labelAudio(probe));
  setText('caption', labelTrack(probe.current, probe.captionsOn), probe.current && (probe.current.translated || probe.captionsOn === false) ? 'warn' : '');
  const vfy = labelVerify(st.verify, settings.doubleCheckLanguage !== false);
  setText('check', vfy.text, vfy.cls);

  const boost = labelBoost(st.diag);
  const lag = labelLag(st.diag);
  const cap = labelCaptured(st.diag);
  const jank = labelJank(st.diag);
  setText('boost', boost.text, boost.cls);
  setText('lag', lag.text, lag.cls);
  setText('track', cap.text, cap.cls);
  setText('jank', jank.text, jank.cls);
  const repairs = st.diag && st.diag.repairs;
  $('diagHint').textContent = repairs
    ? 'De track kwam niet binnen; de ondertiteling is ' + repairs + 'x uit/aan gezet om hem opnieuw op te vragen.'
    : 'Zegt of de ondertiteling uit onze eigen, op de tracktijd gesynchroniseerde weergave komt of uit YouTube\'s (soms achterlopende) venster.';

  const det = L.detectAudioLanguage(probe);
  const plan = L.planFix(probe, {
    detected: det.lang,
    detectedSource: det.source,
    preferAutoGenerated: settings.preferAutoGenerated,
    forceSubtitlesOn: settings.forceSubtitlesOn
  });
  const actionText = plan.action === 'apply'
    ? 'zet ' + L.shortLabel(plan.lang) + ' ' + (plan.target.isAutoGenerated ? 'auto' : 'handmatig') + ' (' + L.describePlan(plan) + ')'
    : L.describePlan(plan);
  setText('action', actionText, plan.action === 'apply' ? 'warn' : (plan.action === 'none' ? 'ok' : 'err'));

  // Een page agent zonder recente frames: het tabblad stond op de achtergrond
  // (Chrome pauzeert rAF en knijpt timers af) of de extensie is herladen
  // zonder de pagina te verversen. Sinds 2026-11-01 hervat de agent zelf bij
  // visibilitychange/focus; blijft het stil, dan is verversen de oplossing.
  const frameAge = st.diag && st.diag.drawing ? st.diag.drawing.frameAgeMs : null;
  if (typeof frameAge === 'number' && frameAge > 10000) {
    setText('action', 'tabblad was inactief - video 10 s vooraan laten spelen', 'warn');
    $('diagHint').textContent = 'Het laatste frame is ' + Math.round(frameAge / 1000) +
      ' s oud: in een tabblad op de achtergrond pauzeert Chrome de frame-lus en de poll. Kom terug naar dit tabblad; de extensie hervat vanzelf. Blijft het stil, ververs dan de pagina (F5) — dat is nodig na een herlaadbeurt van de extensie (⟳).';
  }
}

$('apply').addEventListener('click', async () => {
  const tab = await activeTab();
  if (!tab) return;
  $('apply').textContent = 'Bezig...';
  await sendToTab(tab.id, { type: 'popupRun' });
  setTimeout(() => { $('apply').textContent = 'Nu toepassen'; render(); }, 2500);
});

$('options').addEventListener('click', () => chrome.runtime.openOptionsPage());

// Word-for-Word meteen bewaren: de content script duwt de nieuwe optie direct
// naar de page agent (chrome.storage.onChanged), dus het werkt meteen door.
$('wordByWord').addEventListener('change', () => {
  chrome.storage.sync.set({ captionWordByWord: $('wordByWord').checked });
});

$('recheck').addEventListener('click', async () => {
  $('recheck').textContent = 'Checken...';
  await sendBg({ type: 'bridgeHealth', force: true });
  $('recheck').textContent = 'Bridge checken';
  render();
});

// Diagnose kopiëren: één JSON-blok met alles wat nodig is om een klacht als
// "de ondertiteling loopt achter" te kunnen beoordelen (de page-agent-diagnose
// zegt of wij tekenen en of de track ooit is opgevangen).
$('diagCopy').addEventListener('click', async () => {
  const tab = await activeTab();
  const st = tab ? await sendToTab(tab.id, { type: 'popupState' }) : null;
  const report = {
    at: new Date().toISOString(),
    extensionVersion: chrome.runtime.getManifest().version,
    userAgent: navigator.userAgent,
    url: tab ? tab.url : null,
    diag: st ? st.diag || null : null,
    probe: st ? st.probe || null : null,
    verify: st ? st.verify || null : null
  };
  const text = JSON.stringify(report, null, 2);
  $('diagCopy').textContent = 'Gekopieerd';
  try {
    await navigator.clipboard.writeText(text);
  } catch (e) {
    console.log(text);
    $('diagCopy').textContent = 'Zie console (geen klembord)';
  }
  setTimeout(() => { $('diagCopy').textContent = 'Diagnose kopiëren'; }, 1800);
});

render();
