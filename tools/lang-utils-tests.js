/*
 * SubtitleCorrector - testcases voor de gedeelde pure logica (lang-utils.js).
 *
 * Klassiek script (geen modules) zodat zowel de browser als Node het kan laden:
 *   - browser: tools/test-lang-utils.html
 *   - Node:    node tools/test-lang-utils.mjs
 *
 * De fixtures zijn echte probe-payloads zoals de page agent ze uit YouTube
 * haalt (geverifieerd op 2026-09-12 op een EN- en een NL-video).
 */
(function (root) {
  'use strict';

  var cases = [];

  function test(name, fn) { cases.push({ name: name, fn: fn }); }
  function ok(cond, msg) { if (!cond) throw new Error(msg || 'verwacht true'); }
  function eq(actual, expected, msg) {
    if (actual !== expected) {
      throw new Error((msg ? msg + ': ' : '') + 'verwacht ' + JSON.stringify(expected) + ', kreeg ' + JSON.stringify(actual));
    }
  }
  function clone(o) { return JSON.parse(JSON.stringify(o)); }

  /* ------------------------------------------------------------------ *
   * Fixtures
   * ------------------------------------------------------------------ */

  // 3Blue1Brown (EN audio, handmatige EN-track + EN ASR; YouTube koos de handmatige)
  var PROBE_EN = {
    ok: true,
    videoId: 'aircAruvnKk',
    adShowing: false,
    playerState: 1,
    captionsOn: true,
    audioTrack: { languageCode: 'en', id: 'en.4', name: 'English original', isAutoDubbed: false },
    current: {
      languageCode: 'en', kind: '', vssId: '.en', displayName: 'English',
      isAutoGenerated: false, translated: false, translatedTo: null
    },
    tracks: [
      { languageCode: 'en', kind: '', vssId: '.en', displayName: 'English', isAutoGenerated: false, translated: false },
      { languageCode: 'en', kind: 'asr', vssId: 'a.en', displayName: 'English (auto-generated)', isAutoGenerated: true, translated: false }
    ],
    asrLanguages: ['en'],
    defaultAudioLanguage: null
  };

  // NOS Jeugdjournaal (NL audio, alleen NL ASR; YouTube had naar Engels vertaald)
  var PROBE_NL_TRANSLATED = {
    ok: true,
    videoId: 'gLiU0DiuVro',
    adShowing: false,
    playerState: 1,
    captionsOn: true,
    audioTrack: { languageCode: null, id: 'und', name: 'Default', isAutoDubbed: false },
    current: {
      languageCode: 'nl', kind: 'asr', vssId: 'a.nl', displayName: 'Dutch (auto-generated) >> English',
      isAutoGenerated: true, translated: true, translatedTo: 'en'
    },
    tracks: [
      { languageCode: 'nl', kind: 'asr', vssId: 'a.nl', displayName: 'Dutch (auto-generated)', isAutoGenerated: true, translated: false }
    ],
    asrLanguages: ['nl'],
    defaultAudioLanguage: null
  };

  /* ------------------------------------------------------------------ *
   * Basis-helpers
   * ------------------------------------------------------------------ */
  test('baseLang normaliseert varianten', function (L) {
    eq(L.baseLang('en-US'), 'en');
    eq(L.baseLang('NL_nl'), 'nl');
    eq(L.baseLang('EN'), 'en');
    eq(L.baseLang('de'), 'de');
    eq(L.baseLang(''), null);
  });

  test('isSupported beperkt zich tot EN/NL', function (L) {
    eq(L.isSupported('en-GB'), true);
    eq(L.isSupported('nl'), true);
    eq(L.isSupported('de'), false);
    eq(L.isSupported(null), false);
  });

  test('decodeAudioTrackLang leest "en.4", base64-protobuf en "und"', function (L) {
    eq(L.decodeAudioTrackLang('en.4'), 'en');
    eq(L.decodeAudioTrackLang('nl.2'), 'nl');
    eq(L.decodeAudioTrackLang('pt-BR.1'), 'pt');
    eq(L.decodeAudioTrackLang('und'), null);
    eq(L.decodeAudioTrackLang('251;ChEKBWFjb250EghvcmlnaW5hbAoKCgRsYW5nEgJlbg'), 'en');
    eq(L.decodeAudioTrackLang(null), null);
  });

  test('label-helpers herkennen vertaal-suffixen', function (L) {
    eq(L.isTranslatedLabel('Dutch (auto-generated) >> English'), true);
    eq(L.stripTranslationSuffix('Dutch (auto-generated) >> English'), 'Dutch (auto-generated)');
    eq(L.isTranslatedLabel('English'), false);
  });

  /* ------------------------------------------------------------------ *
   * Track-selectie: prioriteit 1 = auto, prioriteit 2 = handmatig
   * ------------------------------------------------------------------ */
  test('pickCaptionTrack kiest de auto-gegenereerde track (prioriteit 1)', function (L) {
    var pick = L.pickCaptionTrack(PROBE_EN.tracks, 'en', true);
    eq(pick.track.vssId, 'a.en');
    eq(pick.priority, 1);
  });

  test('pickCaptionTrack valt terug op handmatig zonder auto-track', function (L) {
    var pick = L.pickCaptionTrack([PROBE_EN.tracks[0]], 'en', true);
    eq(pick.track.vssId, '.en');
    eq(pick.priority, 2);
  });

  test('pickCaptionTrack negeert vertaalde pseudo-tracks', function (L) {
    var only = [{ languageCode: 'nl', kind: '', vssId: '.nl', displayName: 'Dutch >> English', isAutoGenerated: false, translated: true }];
    eq(L.pickCaptionTrack(only, 'nl', true), null);
  });

  test('pickCaptionTrack respecteert preferAutoGenerated = false', function (L) {
    var pick = L.pickCaptionTrack(PROBE_EN.tracks, 'en', false);
    eq(pick.track.vssId, '.en');
    eq(pick.priority, 2); // prioriteit 1 = auto-gegenereerd, 2 = handmatig
  });

  /* ------------------------------------------------------------------ *
   * Audio-taal detectie
   * ------------------------------------------------------------------ */
  test('detectAudioLanguage: EN-video via de echte audiotrack', function (L) {
    var det = L.detectAudioLanguage(PROBE_EN);
    eq(det.lang, 'en');
    eq(det.source, 'audio-track');
    eq(det.ambiguous, false);
  });

  test('detectAudioLanguage: NL-video zonder audiotrack-info via de ASR-track', function (L) {
    var det = L.detectAudioLanguage(PROBE_NL_TRANSLATED);
    eq(det.lang, 'nl');
    eq(det.ambiguous, false);
  });

  test('detectAudioLanguage: niets bruikbaars -> unknown', function (L) {
    var det = L.detectAudioLanguage({ audioTrack: { languageCode: null }, current: null, tracks: [], asrLanguages: [] });
    eq(det.lang, null);
    eq(det.ambiguous, false);
  });

  test('detectAudioLanguage: tegenstrijdige ASR-talen -> ambiguous', function (L) {
    var det = L.detectAudioLanguage({ audioTrack: { languageCode: null }, current: null, tracks: [], asrLanguages: ['en', 'nl'] });
    eq(det.ambiguous, true);
  });

  test('detectAudioLanguage: niet-EN/NL metadata -> niets (buiten scope)', function (L) {
    var det = L.detectAudioLanguage({ audioTrack: { languageCode: 'de' }, current: null, tracks: [], asrLanguages: ['de'] });
    eq(det.lang, null);
  });

  /* ------------------------------------------------------------------ *
   * planFix
   * ------------------------------------------------------------------ */
  test('planFix: NL-video met Engels vertaalde ondertitel -> zet NL auto', function (L) {
    var plan = L.planFix(PROBE_NL_TRANSLATED, { preferAutoGenerated: true });
    eq(plan.action, 'apply');
    eq(plan.reason, 'translation-active');
    eq(plan.lang, 'nl');
    eq(plan.target.vssId, 'a.nl');
    eq(plan.translatedTo, 'en');
  });

  test('planFix: EN-video met handmatige track -> zet EN auto (prioriteit 1)', function (L) {
    var plan = L.planFix(PROBE_EN, { preferAutoGenerated: true });
    eq(plan.action, 'apply');
    eq(plan.reason, 'wrong-track');
    eq(plan.target.vssId, 'a.en');
    eq(plan.priority, 1);
  });

  test('planFix: alles staat al goed -> none', function (L) {
    var probe = clone(PROBE_EN);
    probe.current = {
      languageCode: 'en', kind: 'asr', vssId: 'a.en', displayName: 'English (auto-generated)',
      isAutoGenerated: true, translated: false, translatedTo: null
    };
    var plan = L.planFix(probe, { preferAutoGenerated: true });
    eq(plan.action, 'none');
    eq(plan.reason, 'already-ok');
  });

  test('planFix: ondertitels uit + forceSubtitlesOn -> apply', function (L) {
    var probe = clone(PROBE_EN);
    probe.captionsOn = false;
    probe.current = null;
    var plan = L.planFix(probe, { preferAutoGenerated: true, forceSubtitlesOn: true });
    eq(plan.action, 'apply');
    eq(plan.reason, 'subtitles-off');
    eq(plan.turnOn, true);
  });

  test('planFix: ondertitels uit en NIET forceren -> niets doen', function (L) {
    var probe = clone(PROBE_EN);
    probe.captionsOn = false;
    probe.current = null;
    var plan = L.planFix(probe, { preferAutoGenerated: true, forceSubtitlesOn: false });
    eq(plan.action, 'none');
    eq(plan.reason, 'captions-off-ignored');
  });

  test('planFix: audio NL maar alleen EN-ondertitels -> no-track', function (L) {
    var probe = {
      ok: true, captionsOn: true, playerState: 1,
      audioTrack: { languageCode: 'nl', id: 'nl.1', name: 'Dutch original' },
      current: null, tracks: [PROBE_EN.tracks[1]], asrLanguages: ['nl'], defaultAudioLanguage: null
    };
    var plan = L.planFix(probe, { preferAutoGenerated: true });
    eq(plan.action, 'no-track');
    eq(plan.lang, 'nl');
  });

  test('planFix: audio-taal onbekend -> unknown', function (L) {
    var probe = {
      ok: true, captionsOn: true, playerState: 1,
      audioTrack: { languageCode: null, id: 'und', name: 'Default' },
      current: null, tracks: [], asrLanguages: [], defaultAudioLanguage: null
    };
    var plan = L.planFix(probe, { preferAutoGenerated: true });
    eq(plan.action, 'unknown');
  });

  test('planFix: audiotaal uit audio-analyse overschrijft metadata', function (L) {
    var probe = {
      ok: true, captionsOn: true, playerState: 1,
      audioTrack: { languageCode: null, id: 'und', name: 'Default' },
      current: {
        languageCode: 'en', kind: 'asr', vssId: 'a.en', displayName: 'English (auto-generated) >> Dutch',
        isAutoGenerated: true, translated: true, translatedTo: 'nl'
      },
      tracks: [
        { languageCode: 'en', kind: 'asr', vssId: 'a.en', displayName: 'English (auto-generated)', isAutoGenerated: true, translated: false },
        { languageCode: 'nl', kind: '', vssId: '.nl', displayName: 'Dutch', isAutoGenerated: false, translated: false }
      ],
      asrLanguages: ['en'],
      defaultAudioLanguage: null
    };
    var plan = L.planFix(probe, { detected: 'nl', detectedSource: 'audio-analysis', preferAutoGenerated: true });
    eq(plan.action, 'apply');
    eq(plan.lang, 'nl');
    eq(plan.source, 'audio-analysis');
    eq(plan.target.vssId, '.nl');
    eq(plan.priority, 2); // geen NL auto-track -> handmatig
  });

  /* ------------------------------------------------------------------ *
   * UI-tekst
   * ------------------------------------------------------------------ */
  test('toastText vertelt wat er is gebeurd', function (L) {
    var plan = L.planFix(PROBE_NL_TRANSLATED, { preferAutoGenerated: true });
    var txt = L.toastText(plan, { ok: true, method: 'menu' });
    ok(txt.indexOf('NL') !== -1, 'taal ontbreekt in: ' + txt);
    ok(txt.indexOf('vertaling stond aan') !== -1, 'reden ontbreekt in: ' + txt);
  });

  /* ------------------------------------------------------------------ *
   * Runner
   * ------------------------------------------------------------------ */
  function run() {
    var results = [];
    for (var i = 0; i < cases.length; i++) {
      var name = cases[i].name;
      try {
        cases[i].fn(root.SCLang);
        results.push({ name: name, ok: true });
      } catch (e) {
        results.push({ name: name, ok: false, error: String((e && e.message) || e) });
      }
    }
    return results;
  }

  root.SCTests = { cases: cases, run: run, fixtures: { PROBE_EN: PROBE_EN, PROBE_NL_TRANSLATED: PROBE_NL_TRANSLATED } };
})(typeof globalThis !== 'undefined' ? globalThis : this);
